"""E001 - full integrity audit of the SCID file. Writes CSV/JSON outputs and a vault note.

    python scripts/run_audit.py            # full file (~1.33B records)
    python scripts/run_audit.py --stop 20000000   # quick partial run
"""
import argparse
import json
import os

import _bootstrap  # noqa: F401
import pandas as pd

from nqresearch import audit, config, manifest as mf, report

ap = argparse.ArgumentParser()
ap.add_argument("--scid")
ap.add_argument("--manifest")
ap.add_argument("--quality-json")
ap.add_argument("--chunk", type=int)
ap.add_argument("--stop", type=int, help="audit only the first N records (smoke test)")
a = ap.parse_args()
cfg = config.load()
scid_path = a.scid or cfg["scid"]
man_path = a.manifest or cfg["manifest"]
qj = a.quality_json or cfg["quality_json"]
out_dir = os.path.join(cfg["work_dir"], "audit")

print(f"Auditing {scid_path}")
aud, summary = audit.run(scid_path, chunk_records=a.chunk or int(cfg["chunk_records"]), stop=a.stop)

boundaries = None
man_err = None
try:
    m = mf.load(man_path)
    summary["manifest_segments"] = len(m)
    boundaries = audit.boundary_report(m, scid_path)
    summary["boundaries_not_at_1800_ET"] = int((boundaries["switch_et_hhmm"] != "18:00").sum())
except Exception as e:  # noqa: BLE001
    man_err = str(e)
    summary["manifest_error"] = man_err

prior = None
if qj and os.path.exists(qj):
    with open(qj) as fh:
        prior = json.load(fh)

paths = audit.write_outputs(aud, summary, out_dir, boundaries)
yt = aud.yearly_table()

expected = {"n_records": 1_333_484_912, "file_size_bytes": 53_339_396_536, "segments": 63,
            "first": "2011-01-02", "last": "2026-07-13"}
cmp_rows = pd.DataFrame([
    {"item": "file size (bytes)", "recorded 2026-07-13": expected["file_size_bytes"], "observed": summary["file_size_bytes"]},
    {"item": "records", "recorded 2026-07-13": expected["n_records"], "observed": summary["n_records"]},
    {"item": "segments", "recorded 2026-07-13": expected["segments"], "observed": summary.get("manifest_segments")},
    {"item": "first trade (UTC)", "recorded 2026-07-13": expected["first"], "observed": summary["first_utc"]},
    {"item": "last trade (UTC)", "recorded 2026-07-13": expected["last"], "observed": summary["last_utc"]},
])

flag_cols = ["year", "records", "pct_flag_buy", "pct_flag_sell", "pct_flag_ambiguous", "pct_vol_ambiguous",
             "side_sum_below", "side_sum_above", "pct_quote_valid", "pct_quote_inside_spread", "flag_vs_quote_agree_pct"]
ts_cols = ["year", "pct_us_nonzero", "pct_eq_ms_prev", "eq_us_prev", "reversals", "rth_gaps_gt_60s",
           "jumps_gt_20pts", "num_trades_ne_1", "zero_volume", "bad_price", "off_tick"]
rec_cols = ["year", "pct_open_single", "pct_open_unbundled", "pct_open_other"] + [c for c in yt.columns if c.startswith("size_")]

rec_table = report.md_table(yt[rec_cols], floatfmt="{:.2f}")
body = f"""# E001 - SCID integrity audit (results)

Generated by `code/scripts/run_audit.py`. Plan and interpretation guide: [[E001 - SCID integrity audit]].
Raw outputs: `{out_dir}`. {"**Partial run** (first %s records)." % f"{a.stop:,}" if a.stop else ""}

## Inventory vs the July 2026 snapshot
{report.md_table(cmp_rows)}

Trailing bytes after last whole record: **{summary['trailing_bytes']}** (must be 0).
Timestamp reversals: **{summary['timestamp_reversals']}** (max {summary['max_reversal_seconds']:.3f} s).
Sessions with data: {summary['sessions_with_data']}; weekday sessions with no data: {summary['missing_weekday_sessions']}
(holidays are expected here; anything else is a hole - see `audit_missing_weekdays.txt`).
{"Manifest could not be loaded: `" + man_err + "`" if man_err else ""}

## Aggressor side by year
Clean flag = all volume on one side. `flag_vs_quote_agree_pct` = share of clean-flag records with the trade
at the bid or ask whose flag agrees with the quote rule. A break in any column between years is a feed /
methodology regime change and must be handled before signed flow is used across it.

{report.md_table(yt[flag_cols])}

## Timestamps and record hygiene by year
`pct_us_nonzero` > 0 means sub-millisecond digits are populated; if `pct_eq_ms_prev` is similar, those digits
are a uniqueness counter, not real time. Use millisecond time only.

{report.md_table(yt[ts_cols])}

## Record type and trade-size mix by year (%)
Trade-size distribution shifts (e.g. after MNQ launched in May 2019, or unbundling changes) make raw trade
counts and "large trade" thresholds non-stationary.

{rec_table}

## Roll boundaries
{report.md_table(boundaries) if boundaries is not None else "_manifest not loaded_"}

## Largest inter-trade gaps (top 30)
{report.md_table(aud.gaps_table().head(30))}

## Largest consecutive-trade price jumps (top 30)
Jumps at roll boundaries are expected (calendar spread). Others are bad ticks or genuine gaps.

{report.md_table(aud.jumps_table().head(30))}

## Prior quality report (for manual comparison)
```json
{json.dumps(prior, indent=1, default=str)[:4000] if prior is not None else "quality json not found at " + str(qj)}
```

## Interpretation (fill in by hand)
- [ ] Inventory matches / explains differences
- [ ] Aggressor flag usable from year ____ ; regime breaks at ____
- [ ] Sub-ms digits: real or counter?
- [ ] Roll boundaries at session open? Gaps sizes plausible?
- [ ] Holes / bad ticks to exclude: ____
"""
note = report.write_note(cfg["vault"], "04 Experiments", "E001 - SCID integrity audit (results)",
                         {"type": "experiment-result", "experiment": "E001", "tags": ["data-audit", "nq"]}, body)
print(json.dumps(summary, indent=2, default=str))
print(f"\nWrote {note}")
for k, v in paths.items():
    print(f"  {k}: {v}")
